/**
 * 获取数据分组对应的字段表头中文名。
 * @param groupKey 数据分组键。
 * @param field 原始字段名。
 * @returns 表头文案。
 */
export function translateField(groupKey: string, field: string): string {
    const groupLabels = GROUP_FIELD_LABELS[groupKey] ?? {}
    const label = groupLabels[field] ?? COMMON_FIELD_LABELS[field] ?? field
    return label
}
